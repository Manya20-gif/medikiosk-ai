export function getTranslation(key, langCode = "en") {
  const code = (langCode || "en").toLowerCase();
  const baseCode = code.split("-")[0];
  const dict = translations[code] || translations[baseCode] || translations.en;
  return dict[key] || translations.en[key] || key;
}

export function useTranslation() {
  const session = useSession();
  const currentLang = session?.languageCode || "en";

  const t = (key, defaultText = "") => {
    return getTranslation(key, currentLang) || defaultText || key;
  };

  return { t, currentLang, setLanguageCode: session?.setLanguageCode };
}
